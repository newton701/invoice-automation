package com.invoiceautomation.export;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.datatype.jsr310.JavaTimeModule;
import com.invoiceautomation.generator.InvoiceData;
import com.invoiceautomation.generator.SourceData;
import com.invoiceautomation.model.*;
import com.invoiceautomation.service.PipelineSummary;
import java.io.IOException;
import java.lang.reflect.RecordComponent;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.*;

/** Exports each generated dataset as CSV and JSON, ground truth separately, and a runnable SQL seed. */
public class DatasetExporter {
    private final ObjectMapper mapper = new ObjectMapper().registerModule(new JavaTimeModule())
            .disable(SerializationFeature.WRITE_DATES_AS_TIMESTAMPS).enable(SerializationFeature.INDENT_OUTPUT);

    public void exportAll(SourceData source, InvoiceData invoiceData, List<MatchResult> matches,
                          List<ExceptionCase> exceptions, List<Approval> approvals,
                          List<Payment> payments, List<InvoiceStatusEvent> events,
                          Path root, PipelineSummary summary) throws IOException {
        Files.createDirectories(root);
        Map<String, List<?>> datasets = new LinkedHashMap<>();
        datasets.put("vendors", source.vendors());
        datasets.put("purchase_orders", source.purchaseOrders());
        datasets.put("po_lines", source.poLines());
        datasets.put("goods_receipts", source.receipts());
        datasets.put("goods_receipt_lines", source.receiptLines());
        datasets.put("invoices", invoiceData.invoices());
        datasets.put("invoice_lines", invoiceData.invoiceLines());
        datasets.put("ground_truth", invoiceData.groundTruth());
        datasets.put("match_results", matches);
        datasets.put("exception_cases", exceptions);
        datasets.put("approvals", approvals);
        datasets.put("payments", payments);
        datasets.put("invoice_status_events", events);
        Path csvDir = root.resolve("csv"); Path jsonDir = root.resolve("json");
        Files.createDirectories(csvDir); Files.createDirectories(jsonDir);
        for (var entry : datasets.entrySet()) {
            writeCsv(entry.getValue(), csvDir.resolve(entry.getKey() + ".csv"));
            mapper.writeValue(jsonDir.resolve(entry.getKey() + ".json").toFile(), entry.getValue());
        }
        // Ground truth is a separate dataset and is not included in invoice input documents.
        mapper.writeValue(root.resolve("pipeline_summary.json").toFile(), summary);
        writeSqlSeed(datasets, root.resolve("seed.sql"));
        mapper.writeValue(root.resolve("dataset_manifest.json").toFile(), buildManifest(datasets));
    }

    private Map<String, Object> buildManifest(Map<String, List<?>> datasets) {
        Map<String, Object> manifest = new LinkedHashMap<>();
        manifest.put("seed", 20261022L);
        Map<String, Object> details = new LinkedHashMap<>();
        datasets.forEach((k,v) -> {
            Map<String, Object> item = new LinkedHashMap<>(); item.put("rows", v.size());
            try { item.put("sha256", sha256(mapper.writeValueAsBytes(v))); }
            catch (Exception e) { item.put("sha256", "ERROR: " + e.getMessage()); }
            details.put(k, item);
        });
        manifest.put("datasets", details);
        return manifest;
    }

    private void writeCsv(List<?> rows, Path path) throws IOException {
        if (rows.isEmpty()) { Files.writeString(path, "", StandardCharsets.UTF_8); return; }
        RecordComponent[] components = rows.get(0).getClass().getRecordComponents();
        StringBuilder out = new StringBuilder();
        for (int i=0;i<components.length;i++) { if(i>0)out.append(','); out.append(csv(components[i].getName())); }
        out.append('\n');
        for (Object row : rows) {
            for (int i=0;i<components.length;i++) {
                if(i>0)out.append(',');
                try { Object value = components[i].getAccessor().invoke(row); out.append(csv(value instanceof Collection<?> c ? String.join(";", c.stream().map(String::valueOf).toList()) : value == null ? "" : String.valueOf(value))); }
                catch (ReflectiveOperationException e) { throw new IOException("Could not export " + row.getClass().getSimpleName(), e); }
            }
            out.append('\n');
        }
        Files.writeString(path, out.toString(), StandardCharsets.UTF_8);
    }

    private void writeSqlSeed(Map<String, List<?>> datasets, Path path) throws IOException {
        StringBuilder sql = new StringBuilder("-- Generated by Invoice Automation; fixed seed: 20261022\n-- Column types are inferred from the Java record components; FK constraints preserve key relationships.\nBEGIN;\n");
        Map<String, String> ids = new HashMap<>();
        ids.put("vendors","vendor_id"); ids.put("purchase_orders","po_id"); ids.put("po_lines","po_line_id");
        ids.put("goods_receipts","grn_id"); ids.put("goods_receipt_lines","grn_line_id"); ids.put("invoices","invoice_id");
        ids.put("invoice_lines","invoice_line_id"); ids.put("ground_truth","invoice_id"); ids.put("match_results","match_id");
        ids.put("exception_cases","case_id"); ids.put("approvals","approval_id"); ids.put("payments","payment_id"); ids.put("invoice_status_events","event_id");
        for (var e : datasets.entrySet()) {
            if (e.getValue().isEmpty()) continue;
            RecordComponent[] c = e.getValue().get(0).getClass().getRecordComponents();
            sql.append("CREATE TABLE IF NOT EXISTS ").append(e.getKey()).append(" (");
            for (int i=0;i<c.length;i++) { if(i>0)sql.append(", "); sql.append(snake(c[i].getName())).append(" ").append(sqlType(c[i].getType())); }
            sql.append(", PRIMARY KEY (").append(ids.getOrDefault(e.getKey(), snake(c[0].getName()))).append("));\n");
        }
        // Explicit FK relationships document the intended relational integrity.
        sql.append("ALTER TABLE purchase_orders ADD CONSTRAINT fk_po_vendor FOREIGN KEY (vendor_id) REFERENCES vendors(vendor_id);\n")
           .append("ALTER TABLE po_lines ADD CONSTRAINT fk_pol_po FOREIGN KEY (po_id) REFERENCES purchase_orders(po_id);\n")
           .append("ALTER TABLE goods_receipts ADD CONSTRAINT fk_gr_po FOREIGN KEY (po_id) REFERENCES purchase_orders(po_id);\n")
           .append("ALTER TABLE goods_receipt_lines ADD CONSTRAINT fk_grl_gr FOREIGN KEY (grn_id) REFERENCES goods_receipts(grn_id);\n")
           .append("ALTER TABLE goods_receipt_lines ADD CONSTRAINT fk_grl_pol FOREIGN KEY (po_line_id) REFERENCES po_lines(po_line_id);\n")
           .append("ALTER TABLE invoices ADD CONSTRAINT fk_inv_vendor FOREIGN KEY (vendor_id) REFERENCES vendors(vendor_id);\n")
           .append("ALTER TABLE invoices ADD CONSTRAINT fk_inv_po FOREIGN KEY (po_id) REFERENCES purchase_orders(po_id);\n")
           .append("ALTER TABLE invoice_lines ADD CONSTRAINT fk_il_inv FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id);\n")
           .append("ALTER TABLE invoice_lines ADD CONSTRAINT fk_il_pol FOREIGN KEY (po_line_id) REFERENCES po_lines(po_line_id);\n")
           .append("ALTER TABLE ground_truth ADD CONSTRAINT fk_gt_inv FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id);\n")
           .append("ALTER TABLE ground_truth ADD CONSTRAINT fk_gt_dup FOREIGN KEY (duplicate_of_invoice_id) REFERENCES invoices(invoice_id);\n")
           .append("ALTER TABLE match_results ADD CONSTRAINT fk_mr_il FOREIGN KEY (invoice_line_id) REFERENCES invoice_lines(invoice_line_id);\n")
           .append("ALTER TABLE exception_cases ADD CONSTRAINT fk_ec_inv FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id);\n")
           .append("ALTER TABLE approvals ADD CONSTRAINT fk_ap_inv FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id);\n")
           .append("ALTER TABLE payments ADD CONSTRAINT fk_pay_inv FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id);\n")
           .append("ALTER TABLE invoice_status_events ADD CONSTRAINT fk_evt_inv FOREIGN KEY (invoice_id) REFERENCES invoices(invoice_id);\n");
        for (var e : datasets.entrySet()) {
            if (e.getValue().isEmpty()) continue;
            RecordComponent[] c = e.getValue().get(0).getClass().getRecordComponents();
            String cols = String.join(",", Arrays.stream(c).map(x -> snake(x.getName())).toList());
            for (Object row : e.getValue()) {
                List<String> values = new ArrayList<>();
                for (RecordComponent component : c) {
                    try {
                        Object v = component.getAccessor().invoke(row);
                        if (v == null) values.add("NULL");
                        else if (v instanceof Number || v instanceof Boolean) values.add(String.valueOf(v));
                        else values.add("'" + sqlValue(v) + "'");
                    }
                    catch (ReflectiveOperationException ex) { throw new IOException("SQL export failed", ex); }
                }
                sql.append("INSERT INTO ").append(e.getKey()).append(" (").append(cols).append(") VALUES (")
                        .append(String.join(",", values)).append(");\n");
            }
        }
        sql.append("COMMIT;\n"); Files.writeString(path, sql.toString(), StandardCharsets.UTF_8);
    }
    private String sqlType(Class<?> type) {
        if (type == int.class || type == Integer.class || type == long.class || type == Long.class) return "INTEGER";
        if (type == boolean.class || type == Boolean.class) return "BOOLEAN";
        if (java.math.BigDecimal.class.isAssignableFrom(type)) return "NUMERIC(14,2)";
        if (java.time.LocalDate.class.isAssignableFrom(type)) return "DATE";
        return "TEXT";
    }
    private String sha256(byte[] bytes) throws Exception {
        byte[] digest = java.security.MessageDigest.getInstance("SHA-256").digest(bytes);
        StringBuilder out = new StringBuilder(); for (byte b : digest) out.append(String.format("%02x", b)); return out.toString();
    }
    private String sqlValue(Object v) { return (v instanceof Collection<?> c ? String.join(";", c.stream().map(String::valueOf).toList()) : String.valueOf(v)).replace("'", "''"); }
    private String snake(String s) { return s.replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase(Locale.ROOT); }
    private String csv(String s) { if (s == null) return ""; return s.contains(",") || s.contains("\"") || s.contains("\n") || s.contains("\r") ? "\"" + s.replace("\"", "\"\"") + "\"" : s; }
}
